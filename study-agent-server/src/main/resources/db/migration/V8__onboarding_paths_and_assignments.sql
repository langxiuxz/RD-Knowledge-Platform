CREATE TABLE sa_onboarding_path (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(128) NOT NULL,
 target_role VARCHAR(128) NULL,
 description VARCHAR(1000) NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 version_no INT UNSIGNED NOT NULL DEFAULT 0,
 knowledge_snapshot_id BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 published_at DATETIME NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_path_project_status(project_id,status,update_time),
 CONSTRAINT fk_path_project FOREIGN KEY(project_id) REFERENCES sa_project(id),
 CONSTRAINT fk_path_snapshot FOREIGN KEY(knowledge_snapshot_id) REFERENCES sa_knowledge_snapshot(id),
 CONSTRAINT fk_path_creator FOREIGN KEY(created_by) REFERENCES sa_user(id),
 CONSTRAINT chk_path_status CHECK(status IN ('DRAFT','PUBLISHED','ARCHIVED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE sa_onboarding_path_task (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 path_id BIGINT UNSIGNED NOT NULL,
 type VARCHAR(16) NOT NULL,
 title VARCHAR(128) NOT NULL,
 description VARCHAR(1000) NULL,
 resource_type VARCHAR(24) NOT NULL,
 resource_id BIGINT UNSIGNED NULL,
 completion_rule VARCHAR(16) NOT NULL,
 estimated_minutes INT UNSIGNED NOT NULL DEFAULT 0,
 required TINYINT(1) NOT NULL DEFAULT 1,
 sort_order INT UNSIGNED NOT NULL DEFAULT 0,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_path_task_order(path_id,sort_order,id),
 CONSTRAINT fk_path_task_path FOREIGN KEY(path_id) REFERENCES sa_onboarding_path(id) ON DELETE CASCADE,
 CONSTRAINT chk_path_task_type CHECK(type IN ('READ','QUIZ','DRILL','CHECKPOINT')),
 CONSTRAINT chk_path_task_resource CHECK(resource_type IN ('DOCUMENT_VERSION','QUIZ','DRILL','NONE')),
 CONSTRAINT chk_path_task_rule CHECK(completion_rule IN ('AUTO','MANUAL'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE sa_onboarding_task_dependency (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 path_id BIGINT UNSIGNED NOT NULL,
 task_id BIGINT UNSIGNED NOT NULL,
 prerequisite_task_id BIGINT UNSIGNED NOT NULL,
 UNIQUE KEY uk_path_dependency(task_id,prerequisite_task_id),
 KEY idx_path_dependency(path_id),
 CONSTRAINT fk_path_dep_path FOREIGN KEY(path_id) REFERENCES sa_onboarding_path(id) ON DELETE CASCADE,
 CONSTRAINT fk_path_dep_task FOREIGN KEY(task_id) REFERENCES sa_onboarding_path_task(id) ON DELETE CASCADE,
 CONSTRAINT fk_path_dep_pre FOREIGN KEY(prerequisite_task_id) REFERENCES sa_onboarding_path_task(id) ON DELETE CASCADE,
 CONSTRAINT chk_path_dep_self CHECK(task_id<>prerequisite_task_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE sa_onboarding_assignment (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 path_id BIGINT UNSIGNED NOT NULL,
 path_version INT UNSIGNED NOT NULL,
 knowledge_snapshot_id BIGINT UNSIGNED NOT NULL,
 assignee_user_id BIGINT UNSIGNED NOT NULL,
 assigned_by BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ASSIGNED',
 progress DECIMAL(5,2) NOT NULL DEFAULT 0,
 due_at DATETIME NULL,
 started_at DATETIME NULL,
 submitted_at DATETIME NULL,
 completed_at DATETIME NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_assignment_assignee(project_id,assignee_user_id,status,create_time),
 KEY idx_assignment_path(path_id,path_version),
 CONSTRAINT fk_assignment_project FOREIGN KEY(project_id) REFERENCES sa_project(id),
 CONSTRAINT fk_assignment_path FOREIGN KEY(path_id) REFERENCES sa_onboarding_path(id),
 CONSTRAINT fk_assignment_snapshot FOREIGN KEY(knowledge_snapshot_id) REFERENCES sa_knowledge_snapshot(id),
 CONSTRAINT fk_assignment_user FOREIGN KEY(assignee_user_id) REFERENCES sa_user(id),
 CONSTRAINT fk_assignment_assigner FOREIGN KEY(assigned_by) REFERENCES sa_user(id),
 CONSTRAINT chk_assignment_status CHECK(status IN ('ASSIGNED','IN_PROGRESS','REVIEW_PENDING','PASSED','NEEDS_WORK','CANCELLED')),
 CONSTRAINT chk_assignment_progress CHECK(progress BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE sa_onboarding_assignment_task (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 assignment_id BIGINT UNSIGNED NOT NULL,
 source_path_task_id BIGINT UNSIGNED NULL,
 type VARCHAR(16) NOT NULL,
 title VARCHAR(128) NOT NULL,
 resource_type VARCHAR(24) NOT NULL,
 resource_id BIGINT UNSIGNED NULL,
 prerequisite_task_ids_json JSON NULL,
 completion_rule VARCHAR(16) NOT NULL,
 required TINYINT(1) NOT NULL DEFAULT 1,
 sort_order INT UNSIGNED NOT NULL DEFAULT 0,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 quiz_attempt_id BIGINT UNSIGNED NULL,
 drill_run_id BIGINT UNSIGNED NULL,
 completion_note VARCHAR(1000) NULL,
 opened_at DATETIME NULL,
 completed_at DATETIME NULL,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_assignment_task_order(assignment_id,sort_order,id),
 CONSTRAINT fk_assignment_task_parent FOREIGN KEY(assignment_id) REFERENCES sa_onboarding_assignment(id) ON DELETE CASCADE,
 CONSTRAINT chk_assignment_task_type CHECK(type IN ('READ','QUIZ','DRILL','CHECKPOINT')),
 CONSTRAINT chk_assignment_task_resource CHECK(resource_type IN ('DOCUMENT_VERSION','QUIZ','DRILL','NONE')),
 CONSTRAINT chk_assignment_task_rule CHECK(completion_rule IN ('AUTO','MANUAL')),
 CONSTRAINT chk_assignment_task_status CHECK(status IN ('LOCKED','PENDING','IN_PROGRESS','COMPLETED','FAILED','SKIPPED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
