CREATE TABLE sa_capability_report (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 assignment_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 report_version INT UNSIGNED NOT NULL DEFAULT 1,
 status VARCHAR(16) NOT NULL DEFAULT 'PROCESSING',
 knowledge_snapshot_id BIGINT UNSIGNED NOT NULL,
 path_version INT UNSIGNED NOT NULL,
 facts_json JSON NOT NULL,
 dimensions_json JSON NULL,
 ai_summary TEXT NULL,
 risks_json JSON NULL,
 recommended_sources_json JSON NULL,
 overall_decision VARCHAR(16) NULL,
 current_task_id VARCHAR(64) NULL,
 model_name VARCHAR(128) NULL,
 error_message VARCHAR(1000) NULL,
 generated_at DATETIME NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_capability_report_assignment_version(assignment_id,report_version),
 KEY idx_capability_report_recovery(status,update_time),
 KEY idx_capability_report_project_user(project_id,user_id,status),
 CONSTRAINT fk_capability_report_project FOREIGN KEY(project_id) REFERENCES sa_project(id),
 CONSTRAINT fk_capability_report_assignment FOREIGN KEY(assignment_id) REFERENCES sa_onboarding_assignment(id),
 CONSTRAINT fk_capability_report_user FOREIGN KEY(user_id) REFERENCES sa_user(id),
 CONSTRAINT fk_capability_report_snapshot FOREIGN KEY(knowledge_snapshot_id) REFERENCES sa_knowledge_snapshot(id),
 CONSTRAINT chk_capability_report_status CHECK(status IN ('PROCESSING','READY','FAILED')),
 CONSTRAINT chk_capability_report_decision CHECK(overall_decision IS NULL OR overall_decision IN ('PASS','NEEDS_WORK'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
